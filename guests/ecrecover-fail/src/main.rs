#![no_std]
#![no_main]
//! S22's failure-path guest: one invalid signature, and the shim returning
//! `None`.
//!
//! The input is `fail_no_curve_point` of
//! `crates/program/tests/vectors/ecrecover.txt`: `r = 5`, whose `x^3 + 7` is
//! `132`, a quadratic non-residue mod `p`, so no curve point has that `x` and
//! the EVM precompile returns empty output. `crates/program/tests/secp256k1.rs`
//! holds the same vector against the `libsecp256k1` oracle.
//!
//! **Failure is a provable outcome, not an unprovable execution**
//! (`docs/spec/ecrecover.md` §1.3): the circuit's success flag is 0, its
//! output words are 0, and the guest runs on to its own exit row. That is what
//! acceptance 5 asks for, and the reason revm can prove a block holding a
//! failed `ecrecover` call.
//!
//! The exit status, `a0`: **5** when the shim answered `None` as it must, and
//! **200** when it answered a key.

use guest_sdk::{ecrecover, entry, exit};

entry!(main);

const HASH: [u8; 32] = [
    0xb6, 0xe1, 0x28, 0x85, 0x27, 0xa6, 0x03, 0x2c, 0x0f, 0x29, 0xc9, 0xda, 0x2c, 0x59, 0x92, 0x02,
    0xcc, 0x25, 0x0f, 0xb4, 0x04, 0xe4, 0x78, 0x38, 0x20, 0xd4, 0xce, 0x0b, 0x09, 0x45, 0x99, 0x89,
];
const V: u8 = 27;
const R: [u8; 32] = [
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05,
];
const S: [u8; 32] = [
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
];

fn main() {
    match ecrecover(&HASH, V, &R, &S) {
        None => exit(5),
        Some(_) => exit(200),
    }
}

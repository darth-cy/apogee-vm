fn main() {
    let mut passed = 0i32;
    for (i, case) in CASES.iter().enumerate() {
        match ecrecover(&case.hash, case.v, &case.r, &case.s) {
            None => exit(210 + i as i32),
            Some(address) => {
                if address != case.address {
                    exit(200 + i as i32);
                }
            }
        }
        passed += 1;
    }
    exit(passed);
}

//! S22's guest: `guest_sdk::ecrecover` over four lines of the committed
//! corpus, checked in-guest against the address the EVM would return.
//!
//! It is the fixture for the secp256k1 recovery delegation family
//! (`docs/spec/ecrecover.md`), and it is the same binary under both executors.
//! Under `crates/emulator` the delegation ecall runs the circuit's function
//! and the invocations reach the `ECRECOVER` trace buffer; under
//! `qemu-riscv32` the same ecall answers `-ENOSYS` and the SDK's software
//! recovery runs instead. **The addresses are the same either way**, which is
//! exactly what acceptance 3 asks: the two paths are bit-identical behind one
//! frozen signature.
//!
//! # The corpus
//!
//! Four lines of `crates/program/tests/vectors/ecrecover.txt`, which
//! `libsecp256k1` and `tiny-keccak` answered
//! (`tools/kat-gen/src/ecrecover.rs`). They cover what acceptance 3 names on
//! the passing side:
//!
//! - **`sign_alpha`** — a signature with `v = 27`;
//! - **`sign_gamma`** — a signature with `v = 28`;
//! - **`high_s_alpha`** — the same signature malleated so `s > n/2`, which the
//!   precompile **accepts**: EIP-2's low-s rule is a transaction-signature
//!   rule and `0x01` does not carry it. It recovers `sign_alpha`'s address;
//! - **`r_one`** — `r` and `s` both 1, the bottom of their range.
//!
//! `crates/emulator/tests/guests.rs` reads these literals out of this file and
//! holds them to the committed corpus, so a stale vector here cannot pass.
//!
//! # fd 0, fd 1, fd 2, fd 3
//!
//! Unused, for `keccak-test`'s reason: `EXIT` and the delegation calls are the
//! only provable ecalls, so a `write` would make the fixture unprovable.
//!
//! # The result
//!
//! The exit status, `a0`: **4**, one per check passed, or `200 + i` on the
//! first mismatch — which names the corpus entry rather than leaving a count
//! one short of what it should be. `210 + i` if the shim returned `None` where
//! the corpus says a key: a different failure from a wrong address, and worth
//! telling apart.


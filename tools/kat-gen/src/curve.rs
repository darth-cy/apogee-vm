//! The Fq tower and curve-group fixtures, generated against arkworks-bn254.
//!
//! Three files, all written to `crates/curve/tests/vectors/`:
//!
//! * `fq_kats.txt` — Fq and Fq2 arithmetic: an edge grid, 1,000 random
//!   vectors per field, `pow`, and the wire-canonicity cases.
//! * `g1_kats.txt` — G1: the generator's exact bytes, 1,000 random
//!   `(P, Q, k)` vectors, the addition and scalar edge cases, and every
//!   rejection class `from_bytes` has to catch.
//! * `g2_kats.txt` — the same for G2, plus on-curve points outside the
//!   order-`r` subgroup, which G1 cannot have.
//!
//! Every expected value comes from arkworks. Nothing here is `crates/curve`'s
//! own answer read back.
//!
//! # Encoding
//!
//! One token per value, in the wire form `crates/curve` emits: 64 hex
//! characters for an `Fq`, 128 for an `Fq2` (`c0 || c1`), 128 for a G1 point
//! (`x || y`), 256 for a G2 point, each coordinate canonical little-endian.
//! All-zero is the point at infinity. A value that does not exist — the
//! inverse of zero, the root of a nonresidue — is the token `none`, so every
//! line kind has a fixed arity.
//!
//! Point tokens are therefore also a wire-format fixture: the tests parse them
//! coordinate-wise rather than through `from_bytes`, because the off-curve and
//! out-of-subgroup lines are exactly the values `from_bytes` must reject.

use std::fmt::Write as _;

use ark_bn254::{Fq, Fq2, Fr, G1Affine, G1Projective, G2Affine, G2Projective};
use ark_ec::{AffineRepr, CurveGroup, PrimeGroup};
use ark_ff::{AdditiveGroup, BigInteger, Field, One, PrimeField};
use test_support::{to_hex, Rng};

use crate::shared::{hex_exp, hex_fq, hex_fq2, hex_fr, hex_g1, hex_g2, opt_fq, opt_fq2};

const FQ_SEED: u64 = 20260910;
const G1_SEED: u64 = 20260911;
const G2_SEED: u64 = 20260912;

/// Acceptance 1 and 3 both ask for at least a thousand random vectors.
const RANDOM_VECTORS: usize = 1_000;

// ---------------------------------------------------------------------------
// Sampling
// ---------------------------------------------------------------------------

/// Reduced mod q, not rejection-sampled: the vectors want arkworks' own answer
/// for an arbitrary 256-bit input.
fn next_fq(rng: &mut Rng) -> Fq {
    Fq::from_le_bytes_mod_order(&rng.next_le32())
}

fn next_fq2(rng: &mut Rng) -> Fq2 {
    Fq2::new(next_fq(rng), next_fq(rng))
}

fn next_fr(rng: &mut Rng) -> Fr {
    Fr::from_le_bytes_mod_order(&rng.next_le32())
}

/// A uniform point of the order-`r` subgroup: `k * G` for uniform `k`.
fn next_g1(rng: &mut Rng) -> G1Affine {
    (G1Projective::generator() * next_fr(rng)).into_affine()
}

fn next_g2(rng: &mut Rng) -> G2Affine {
    (G2Projective::generator() * next_fr(rng)).into_affine()
}


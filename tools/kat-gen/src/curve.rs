fn g2_rejections(rng: &mut Rng) -> Vec<Rejection> {
    let q_hex = to_hex(&Fq::MODULUS.to_bytes_le());
    let mut out = Vec::new();

    // On-curve, outside the order-r subgroup: a random x with the cofactor
    // left un-cleared. G1 cannot have these -- its cofactor is 1 -- which is
    // why acceptance 5's G1 half uses off-curve points instead.
    let b2 = <ark_bn254::g2::Config as ark_ec::short_weierstrass::SWCurveConfig>::COEFF_B;
    let mut found = 0;
    while found < 4 {
        let x = next_fq2(rng);
        let Some(y) = (x * x * x + b2).sqrt() else {
            continue;
        };
        let point = G2Affine::new_unchecked(x, y);
        assert!(point.is_on_curve(), "constructed from the curve equation");
        assert!(
            !point.is_in_correct_subgroup_assuming_on_curve(),
            "an un-cleared random point is almost never in the subgroup"
        );
        out.push(Rejection {
            hex: hex_g2(&point),
            reason: "not_in_subgroup",
        });
        found += 1;
    }

    // Must-be-exact 3's fourth class, once per coordinate half.
    let zeros = to_hex(&[0u8; 32]);
    let one = hex_fq(&Fq::one());
    for half in 0..4 {
        let hex: String = (0..4)
            .map(|i| {
                if i == half {
                    one.as_str()
                } else {
                    zeros.as_str()
                }
            })
            .collect();
        out.push(Rejection {
            hex,
            reason: "nonzero_infinity_pattern",
        });
    }

    for _ in 0..2 {
        let p = next_g2(rng);
        let bad_y = p.y + Fq2::one();
        assert_ne!(bad_y, -p.y);
        assert!(
            !G2Affine::new_unchecked(p.x, bad_y).is_on_curve(),
            "y + 1 must leave the curve"
        );
        out.push(Rejection {
            hex: format!("{}{}", hex_fq2(&p.x), hex_fq2(&bad_y)),
            reason: "off_curve",
        });
    }

    let p = next_g2(rng);
    out.push(Rejection {
        hex: format!("{}{}{}", q_hex, zeros, hex_fq2(&p.y)),
        reason: "non_canonical_x",
    });
    out.push(Rejection {
        hex: format!("{}{}{}", zeros, q_hex, hex_fq2(&p.y)),
        reason: "non_canonical_x",
    });
    out.push(Rejection {
        hex: format!("{}{}{}", hex_fq2(&p.x), q_hex, zeros),
        reason: "non_canonical_y",
    });
    out.push(Rejection {
        hex: format!("{}{}{}", hex_fq2(&p.x), zeros, q_hex),
        reason: "non_canonical_y",
    });
    out
}


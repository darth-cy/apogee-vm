// fq6_kats.txt
// ---------------------------------------------------------------------------

const FQ6_HEADER: &str = "\
# fq6_kats v1 -- BN254 Fq6 known-answer tests
# generated by tools/kat-gen against ark-bn254 0.6; do not edit by hand
# regenerate: cargo run -p kat-gen -- tower
# seed: 20260913 (splitmix64)
#
# Fq6 = Fq2[v]/(v^3 - xi), xi = 9 + u. One token per value: 384 hex characters
# written c0 || c1 || c2, each Fq2 being 128 characters of canonical
# little-endian Fq written c0 || c1. A value that does not exist is the token
# `none`, so every line kind has a fixed arity.
#
#   fq6_ops  <a> <b> <a+b> <a-b> <a*b> <a^2> <1/a> <a*v> <a^q> <a^(q^2)> <a^(q^3)>
#   fq6_frob <a> <i> <a^(q^i)>     i in 0..6, so every Frobenius table entry is read
#   fq6_pow  <a> <e> <a^e>         e is a plain 256-bit integer, not reduced
#
# Fq6 has no `conjugate`: it is a cubic extension of Fq2 and has no order-two
# automorphism over it. Conjugation lives on Fq12, in fq12_kats.txt.
";

fn fq6_ops_line(out: &mut String, a: &Fq6, b: &Fq6) {
    let mut v = Fq6::ZERO;
    v.c1 = Fq2::ONE;
    let _ = writeln!(
        out,
        "fq6_ops {} {} {} {} {} {} {} {} {} {} {}",
        hex_fq6(a),
        hex_fq6(b),
        hex_fq6(&(*a + *b)),
        hex_fq6(&(*a - *b)),
        hex_fq6(&(*a * *b)),
        hex_fq6(&a.square()),
        opt_fq6(a.inverse()),
        hex_fq6(&(*a * v)),
        hex_fq6(&frobenius6(a, 1)),
        hex_fq6(&frobenius6(a, 2)),
        hex_fq6(&frobenius6(a, 3)),
    );
}

fn frobenius6(a: &Fq6, power: usize) -> Fq6 {
    let mut out = *a;
    out.frobenius_map_in_place(power);
    out
}

fn fq6_kats() -> String {
    let mut out = String::from(FQ6_HEADER);
    let mut rng = Rng::new(FQ6_SEED);
    let edges = fq6_edges();

    out.push_str("\n# --- the edge grid ---\n");
    for a in &edges {
        for b in &edges {
            fq6_ops_line(&mut out, a, b);
        }
    }

    out.push_str("\n# --- random pairs ---\n");
    let mut seen = Vec::new();
    for _ in 0..RANDOM_VECTORS {
        let (a, b) = (next_fq6(&mut rng), next_fq6(&mut rng));
        seen.push(hex_fq6(&a));
        fq6_ops_line(&mut out, &a, &b);
    }
    crate::assert_distinct(&seen, "random Fq6 elements");

    // Random elements first, then the edges. A Frobenius line only exercises a
    // table entry when the coefficient that entry multiplies is nonzero, so the
    // generic elements are the ones that read the table -- and they are what a
    // reader, or the corruption sweep in `tests/kats.rs`, should meet first.
    out.push_str("\n# --- the Frobenius at every power: random elements, then the edges ---\n");
    let mut samples: Vec<Fq6> = (0..FROBENIUS_SAMPLES).map(|_| next_fq6(&mut rng)).collect();
    samples.extend(edges.iter().copied());
    for a in &samples {
        for i in 0..6 {
            let _ = writeln!(
                out,
                "fq6_frob {} {} {}",
                hex_fq6(a),
                i,
                hex_fq6(&frobenius6(a, i))
            );
        }
    }

    out.push_str("\n# --- pow on the edge grid with fixed exponents ---\n");
    for a in &edges {
        for e in FIXED_EXPONENTS {
            let _ = writeln!(
                out,
                "fq6_pow {} {} {}",
                hex_fq6(a),
                hex_exp(&e),
                hex_fq6(&a.pow(e))
            );
        }
    }
    out.push_str("\n# --- pow on random bases and exponents ---\n");
    for _ in 0..40 {
        let a = next_fq6(&mut rng);
        let e = rng.next_exp();
        let _ = writeln!(
            out,
            "fq6_pow {} {} {}",
            hex_fq6(&a),
            hex_exp(&e),
            hex_fq6(&a.pow(e))
        );
    }

    out
}


//! The Fq6 and Fq12 fixtures, generated against arkworks-bn254.
//!
//! Two files, both written to `crates/curve/tests/vectors/`:
//!
//! * `fq6_kats.txt` — Fq6 arithmetic: an edge grid, 1,000 random vectors,
//!   the Frobenius at every power `0..6`, and `pow`.
//! * `fq12_kats.txt` — the same for Fq12, with `conjugate` in place of
//!   `mul_by_nonresidue`, the Frobenius at every power `0..12`, and the
//!   final exponentiation.
//!
//! # Encoding
//!
//! One token per value, extending the convention `curve.rs` set: 64 hex
//! characters of canonical little-endian `Fq`, concatenated in coefficient
//! order. So an `Fq2` is 128 characters, an `Fq6` 384 written
//! `c0 || c1 || c2`, and an `Fq12` 768 written `c0 || c1`. A value that does
//! not exist is the token `none`, so every line kind has a fixed arity.
//!
//! # The final exponentiation is the literal exponent
//!
//! `fq12_final_exp` raises to `(q^12 - 1)/r` computed as an integer, **not**
//! to whatever `ark_bn254::Bn254::final_exponentiation` returns. arkworks
//! uses the Fuentes-Castañeda variant, which produces `f^(m d)` for a fixed
//! `m = 2x(6x^2 + 3x + 1)` rather than `f^d`, and S06 requires the exact
//! power. The relationship is asserted here rather than assumed, so a change
//! in either direction is caught at generation time.

use std::fmt::Write as _;

use ark_bn254::{Fq, Fq12, Fq2, Fq6, Fr};
use ark_ff::{AdditiveGroup, Field, One, PrimeField, Zero};
use num_bigint::BigUint;
use test_support::Rng;

use crate::shared::{
    full_final_exponent, hex_exp, hex_fq12, hex_fq6, opt_fq12, opt_fq6, FIXED_EXPONENTS,
};

const FQ6_SEED: u64 = 20260913;
const FQ12_SEED: u64 = 20260914;

/// Acceptance 1 asks for at least a thousand random vectors per operation.
const RANDOM_VECTORS: usize = 1_000;
/// Elements carried through every Frobenius power, on top of the edge set.
const FROBENIUS_SAMPLES: usize = 12;
/// Inputs to the exact `(q^12 - 1)/r` exponentiation. Not an Acceptance-1 op,
/// and each one costs a 2,790-bit ladder on both sides, so this is a smaller
/// corpus than the arithmetic above.
const FINAL_EXP_SAMPLES: usize = 200;

// ---------------------------------------------------------------------------
// Sampling
// ---------------------------------------------------------------------------

fn next_fq(rng: &mut Rng) -> Fq {
    Fq::from_le_bytes_mod_order(&rng.next_le32())
}

fn next_fq2(rng: &mut Rng) -> Fq2 {
    Fq2::new(next_fq(rng), next_fq(rng))
}

fn next_fq6(rng: &mut Rng) -> Fq6 {
    Fq6::new(next_fq2(rng), next_fq2(rng), next_fq2(rng))
}

fn next_fq12(rng: &mut Rng) -> Fq12 {
    Fq12::new(next_fq6(rng), next_fq6(rng))
}

fn xi() -> Fq2 {
    let xi = <ark_bn254::Fq6Config as ark_ff::fields::Fp6Config>::NONRESIDUE;
    assert_eq!(xi, Fq2::new(Fq::from(9u64), Fq::one()), "xi must be 9 + u");
    xi
}

/// Eight Fq6 edges: zero, one, the two pure powers of `v`, the nonresidue
/// itself, and three elements with a zero sub-component in each position.
fn fq6_edges() -> Vec<Fq6> {
    let (z, o, m) = (Fq2::ZERO, Fq2::ONE, -Fq2::ONE);
    let u = Fq2::new(Fq::ZERO, Fq::one());
    vec![
        Fq6::new(z, z, z),
        Fq6::new(o, z, z),
        Fq6::new(z, o, z),
        Fq6::new(z, z, o),
        Fq6::new(xi(), z, z),
        Fq6::new(o, z, o),
        Fq6::new(z, o, o),
        Fq6::new(m, u, -u),
    ]
}

/// Eight Fq12 edges, on the same principle one level up.
fn fq12_edges() -> Vec<Fq12> {
    let e = fq6_edges();
    let (z, o) = (Fq6::ZERO, Fq6::ONE);
    vec![
        Fq12::new(z, z),
        Fq12::new(o, z),
        Fq12::new(z, o),
        Fq12::new(o, o),
        Fq12::new(e[2], z),
        Fq12::new(z, e[2]),
        Fq12::new(e[4], -o),
        Fq12::new(e[5], e[7]),
    ]
}


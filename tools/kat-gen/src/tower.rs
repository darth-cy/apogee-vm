const FQ12_HEADER: &str = "\
# fq12_kats v1 -- BN254 Fq12 known-answer tests
# generated by tools/kat-gen against ark-bn254 0.6; do not edit by hand
# regenerate: cargo run -p kat-gen -- tower
# seed: 20260914 (splitmix64)
#
# Fq12 = Fq6[w]/(w^2 - v). One token per value: 768 hex characters written
# c0 || c1, each Fq6 being 384 characters. A value that does not exist is the
# token `none`, so every line kind has a fixed arity.
#
#   fq12_ops  <a> <b> <a+b> <a-b> <a*b> <a^2> <1/a> <conj a> <a^q> <a^(q^2)> <a^(q^3)>
#   fq12_frob <a> <i> <a^(q^i)>   i in 0..12, so every Frobenius table entry is read
#   fq12_pow  <a> <e> <a^e>       e is a plain 256-bit integer, not reduced
#   fq12_final_exp <a> <a^((q^12-1)/r)>
#
# The final exponent is the literal integer (q^12 - 1)/r, 2,790 bits, applied
# by square-and-multiply. It is NOT ark_bn254's own final_exponentiation, which
# returns the Fuentes-Castaneda power f^(m d) with m = 2x(6x^2 + 3x + 1); the
# generator asserts that relationship rather than assuming it.
";

fn frobenius12(a: &Fq12, power: usize) -> Fq12 {
    let mut out = *a;
    out.frobenius_map_in_place(power);
    out
}

fn fq12_ops_line(out: &mut String, a: &Fq12, b: &Fq12) {
    let mut conj = *a;
    conj.conjugate_in_place();
    let _ = writeln!(
        out,
        "fq12_ops {} {} {} {} {} {} {} {} {} {} {}",
        hex_fq12(a),
        hex_fq12(b),
        hex_fq12(&(*a + *b)),
        hex_fq12(&(*a - *b)),
        hex_fq12(&(*a * *b)),
        hex_fq12(&a.square()),
        opt_fq12(a.inverse()),
        hex_fq12(&conj),
        hex_fq12(&frobenius12(a, 1)),
        hex_fq12(&frobenius12(a, 2)),
        hex_fq12(&frobenius12(a, 3)),
    );
}

fn fq12_kats() -> String {
    let mut out = String::from(FQ12_HEADER);
    let mut rng = Rng::new(FQ12_SEED);
    let edges = fq12_edges();

    out.push_str("\n# --- the edge grid ---\n");
    for a in &edges {
        for b in &edges {
            fq12_ops_line(&mut out, a, b);
        }
    }

    out.push_str("\n# --- random pairs ---\n");
    let mut seen = Vec::new();
    for _ in 0..RANDOM_VECTORS {
        let (a, b) = (next_fq12(&mut rng), next_fq12(&mut rng));
        seen.push(hex_fq12(&a));
        fq12_ops_line(&mut out, &a, &b);
    }
    crate::assert_distinct(&seen, "random Fq12 elements");

    // Random elements first; see the note in `fq6_kats`.
    out.push_str("\n# --- the Frobenius at every power: random elements, then the edges ---\n");
    let mut samples: Vec<Fq12> = (0..FROBENIUS_SAMPLES)
        .map(|_| next_fq12(&mut rng))
        .collect();
    samples.extend(edges.iter().copied());
    for a in &samples {
        for i in 0..12 {
            let _ = writeln!(
                out,
                "fq12_frob {} {} {}",
                hex_fq12(a),
                i,
                hex_fq12(&frobenius12(a, i))
            );
        }
    }

    out.push_str("\n# --- pow on the edge grid with fixed exponents ---\n");
    for a in &edges {
        for e in FIXED_EXPONENTS {
            let _ = writeln!(
                out,
                "fq12_pow {} {} {}",
                hex_fq12(a),
                hex_exp(&e),
                hex_fq12(&a.pow(e))
            );
        }
    }
    out.push_str("\n# --- pow on random bases and exponents ---\n");
    for _ in 0..40 {
        let a = next_fq12(&mut rng);
        let e = rng.next_exp();
        let _ = writeln!(
            out,
            "fq12_pow {} {} {}",
            hex_fq12(&a),
            hex_exp(&e),
            hex_fq12(&a.pow(e))
        );
    }

    out.push_str("\n# --- the exact final exponentiation ---\n");
    let exponent = full_final_exponent();
    let m = fuentes_castaneda_multiplier();
    for a in edges
        .iter()
        .filter(|a| !Zero::is_zero(*a))
        .copied()
        .chain((0..FINAL_EXP_SAMPLES).map(|_| next_fq12(&mut rng)))
    {
        let value = a.pow(&exponent);
        // The output has order dividing r, and arkworks' own routine returns
        // the fixed power of it that Must-be-exact 6 forbids. Both checked,
        // so a change in either is caught here and not in a test.
        assert_eq!(
            value.pow(Fr::MODULUS.0),
            Fq12::one(),
            "the final exponentiation lands in the order-r subgroup"
        );
        assert_eq!(
            ark_final_exponentiation(&a),
            value.pow(&m),
            "arkworks' final exponentiation must be the Fuentes-Castaneda power"
        );
        let _ = writeln!(out, "fq12_final_exp {} {}", hex_fq12(&a), hex_fq12(&value));
    }

    out
}

/// `ark_ec`'s BN final exponentiation, reached through the pairing engine.
fn ark_final_exponentiation(f: &Fq12) -> Fq12 {
    <ark_bn254::Config as ark_ec::bn::BnConfig>::final_exponentiation(
        ark_ec::pairing::MillerLoopOutput(*f),
    )
    .expect("a nonzero Fq12 has a final exponentiation")
    .0
}

/// `m = 2x(6x^2 + 3x + 1)`, the fixed multiplier the Fuentes-Castañeda hard
/// part introduces, reduced mod `r` — which is exact on a value whose order
/// divides `r`.
fn fuentes_castaneda_multiplier() -> Vec<u64> {
    let x = BigUint::from(constants::BN_PARAMETER_X);
    let m = 2u32 * &x * (6u32 * &x * &x + 3u32 * &x + 1u32);
    (m % BigUint::from(Fr::MODULUS)).to_u64_digits()
}

// ---------------------------------------------------------------------------

pub fn generate() {
    crate::write_vectors("crates/curve/tests/vectors/fq6_kats.txt", &fq6_kats());
    crate::write_vectors("crates/curve/tests/vectors/fq12_kats.txt", &fq12_kats());
}
